// Traced from the cutout PNG alpha masks. Points are normalised to the canvas
// (6% margin). The canvas is sized to the fish's aspect ratio, so nothing is
// stretched.
function tracePath(ctx: CanvasRenderingContext2D, pts: number[], w: number, h: number) {
  ctx.beginPath();
  ctx.moveTo(pts[0] * w, pts[1] * h);
  for (let i = 2; i < pts.length; i += 2) ctx.lineTo(pts[i] * w, pts[i + 1] * h);
  ctx.closePath();
}

